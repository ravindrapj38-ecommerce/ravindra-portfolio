// Copies the data the TypeScript core shares with the Python engine into lib/core/generated/.
// Sources: veritext-stem/shared/*.json and services/engine/prompts/. Run after editing either;
// tests/shared-sync.test.ts fails if the generated copy is stale.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const out = join(here, "..", "lib", "core", "generated");

export function buildShared() {
  const read = (p) => readFileSync(join(root, p), "utf8");
  const json = (p) => JSON.parse(read(p));
  const prompt = (name) => read(`services/engine/prompts/${name}/v1.md`).split("---").slice(2).join("---").trim();
  return {
    lexicons: json("shared/lexicons.json"),
    lockPatterns: json("shared/lock_patterns.json").rules,
    aiPhrases: json("shared/ai_phrases.json").phrases,
    demoSubstitutions: json("shared/demo_rewrites.json").substitutions,
    sample: read("shared/sample.md"),
    prompts: { rewrite: prompt("rewrite"), repair: prompt("repair") },
    styles: parse(read("services/engine/prompts/rewrite/styles.yaml")),
  };
}

export function renderShared() {
  return (
    "// GENERATED by scripts/sync-shared.mjs from veritext-stem/shared and services/engine/prompts. Do not edit.\n" +
    "import type { SharedData } from \"../types\";\n" +
    `const shared: SharedData = ${JSON.stringify(buildShared(), null, 1)};\nexport default shared;\n`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, "shared.ts"), renderShared());
  console.log("wrote lib/core/generated/shared.ts");
}
